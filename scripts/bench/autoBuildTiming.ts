import type { AutoBuildLimits, AutoBuildResult, Lineup, LineupEntry, MeetEvent, MeetModel, RelaySplit, RulePreset, ScorerTag } from '@omniswim/engine';
import { adaptSimulatorSnapshot } from '@omniswim/swimcloud/browser';
import { buildSnapshot } from '../../tests/helpers/simulatorFixtures';
import { nodeMipSolve } from '../../tests/helpers/nodeMipSolve';
import { scaleTeams } from './lib/scaleTeams';

interface Scenario {
  readonly title: string;
  readonly model: MeetModel;
  readonly lineup: Lineup;
  readonly own: string;
}

const argValue = (flag: string, fallback: number): number => {
  const i = process.argv.indexOf(flag);
  const n = i >= 0 ? Number(process.argv[i + 1]) : fallback;
  if (!Number.isInteger(n) || n < 1) throw new Error(`${flag} needs a positive integer`);
  return n;
};
const RUNS = argValue('--runs', 3);
const TEAMS = argValue('--teams', 10);
const SWEEP = process.argv.includes('--sweep');
const SOURCING = { includeConvertedSwims: false, lcmToScy: null } as const;

const median = (xs: readonly number[]): number => {
  const s = [...xs].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length === 0 ? NaN : s.length % 2 ? (s[m] as number) : ((s[m - 1] as number) + (s[m] as number)) / 2;
};

function configC(): Scenario {
  const { snapshot } = buildSnapshot('C');
  const adapted = adaptSimulatorSnapshot(snapshot, { meetKey: 'bench-config-C', snapshotId: 'bench' });
  if (adapted.kind !== 'ready') throw new Error(`config C did not adapt: ${adapted.kind}`);
  const { model, lineup } = adapted.adapted;
  const own = String(model.teams.find((t) => String(t.teamId) === '58')?.teamId ?? (model.teams[0] as { teamId: string }).teamId);
  const scaled = scaleTeams(model, lineup, TEAMS);
  return { title: `config C at ${scaled.model.teams.length} teams (recorded teams copied under new ids; recorded times unchanged)`, model: scaled.model, lineup: scaled.lineup, own };
}

/** mulberry32: a fixed generator, so the SYNTHETIC field is the same on every run. */
function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const INDIVIDUAL = ['50 Freestyle', '100 Freestyle', '200 Freestyle', '500 Freestyle', '1000 Freestyle', '100 Backstroke', '200 Backstroke', '100 Breaststroke', '200 Breaststroke', '100 Butterfly', '200 Butterfly', '200 Individual Medley', '400 Individual Medley', '50 Backstroke', '50 Breaststroke', '50 Butterfly'];
const DIVES = ['1-Meter Diving', '3-Meter Diving'];
const RELAYS: readonly { key: string; legs: readonly string[]; kind: 'medley' | 'free' }[] = [
  { key: '200 Medley Relay', legs: ['50 Backstroke', '50 Breaststroke', '50 Butterfly', '50 Freestyle'], kind: 'medley' },
  { key: '200 Freestyle Relay', legs: ['50 Freestyle', '50 Freestyle', '50 Freestyle', '50 Freestyle'], kind: 'free' },
];

/** SYNTHETIC: ten teams of 14 swimmers, 16 individual events, 2 dives, 2 relays. Every time is generated here. */
function synthetic(): Scenario {
  const rand = rng(20261029);
  const teams = Array.from({ length: TEAMS }, (_, i) => `S${i}`);
  const swimmers: MeetModel['swimmers'][number][] = [];
  const swims: MeetModel['swims'][number][] = [];
  const splits: RelaySplit[] = [];
  const events: MeetEvent[] = [
    ...INDIVIDUAL.map((eventKey) => ({ eventKey, gender: 'Men' as const, kind: 'individual' as const, distanceYards: 100, relayKind: null })),
    ...DIVES.map((eventKey) => ({ eventKey, gender: 'Men' as const, kind: 'diving' as const, distanceYards: null, relayKind: null })),
    ...RELAYS.map((r) => ({ eventKey: r.key, gender: 'Men' as const, kind: 'relay' as const, distanceYards: 200, relayKind: r.kind })),
  ];
  const addSwim = (swimmerId: string, eventKey: string, hundredths: number): void => {
    swims.push({
      swimId: `${swimmerId}:${eventKey}`,
      swimmerId,
      eventKey,
      recordedCourse: 'SCY',
      recordedTime: { text: (hundredths / 100).toFixed(2), hundredths },
      date: null,
      seasonId: null,
      flags: {},
      scy: { kind: 'recorded-scy' },
      origin: { kind: 'simulator', snapshotId: 'synthetic' },
    });
  };
  for (const team of teams) {
    for (let i = 0; i < 14; i++) {
      const swimmerId = `${team}s${String(i).padStart(2, '0')}`;
      swimmers.push({ swimmerId, teamId: team, gender: 'Men', classYear: null, roster: 'member' });
      for (const eventKey of INDIVIDUAL) if (rand() < 0.6) addSwim(swimmerId, eventKey, 2000 + Math.floor(rand() * 4000));
      for (const eventKey of DIVES) if (rand() < 0.2) addSwim(swimmerId, eventKey, 15000 + Math.floor(rand() * 15000));
      for (const leg of ['50 Breaststroke', '50 Butterfly', '50 Freestyle']) {
        splits.push({ splitId: `${swimmerId}:${leg}`, swimmerId, relayEventKey: null, legPosition: null, start: 'flying', legEventKey: leg, split: { text: '0', hundredths: 2300 + Math.floor(rand() * 600) }, course: 'SCY', date: null, origin: { kind: 'simulator', snapshotId: 'synthetic' } });
      }
    }
  }
  const model: MeetModel = {
    payloadVersion: 1,
    meetKey: 'bench-synthetic',
    teams: teams.map((teamId) => ({ teamId, division: { state: 'unknown', reason: 'unmapped_team' } })),
    swimmers,
    events,
    swims,
    relaySplits: splits,
    recordRange: { kind: 'seasons', seasonIds: ['2025-26'] },
    extendedWindow: false,
    observedScores: null,
  };
  const entries: LineupEntry[] = [];
  for (const team of teams) {
    const mine = swimmers.filter((s) => s.teamId === team);
    for (const s of mine) {
      for (const eventKey of [...INDIVIDUAL, ...DIVES]) {
        if (swims.some((w) => w.swimmerId === s.swimmerId && w.eventKey === eventKey) && rand() < 0.5) {
          entries.push({ kind: 'individual', teamId: team, swimmerId: s.swimmerId, eventKey, gender: 'Men', seedSwimId: null });
        }
      }
    }
    // Two relays of each kind per team.
    for (const relay of RELAYS) {
      const shuffled = [...mine].sort(() => rand() - 0.5);
      for (const [letter, group] of [['A', shuffled.slice(0, 4)], ['B', shuffled.slice(4, 8)]] as const) {
        entries.push({
          kind: 'relay',
          teamId: team,
          eventKey: relay.key,
          gender: 'Men',
          letter,
          legs: group.map((s, i) => ({
            swimmerId: s.swimmerId,
            basis: i === 0 ? { kind: 'flat-start-swim' as const, swimId: `${s.swimmerId}:${relay.legs[0]}` } : { kind: 'split' as const, splitId: `${s.swimmerId}:${relay.legs[i]}` },
          })) as unknown as Extract<LineupEntry, { kind: 'relay' }>['legs'],
        });
      }
    }
  }
  // The leg-1 flat swims every relay names.
  for (const s of swimmers) for (const leg of ['50 Backstroke', '50 Freestyle']) if (!swims.some((w) => w.swimId === `${s.swimmerId}:${leg}`)) addSwim(s.swimmerId, leg, 2600 + Math.floor(rand() * 600));
  return { title: `SYNTHETIC 20-event field: ${TEAMS} generated teams of 14 swimmers (every time generated by this script)`, model, lineup: { payloadVersion: 1, meetKey: model.meetKey, entries }, own: 'S0' };
}

function tagsFor(sc: Scenario): ScorerTag[] {
  const own = sc.model.swimmers.filter((s) => s.teamId === sc.own && s.gender === 'Men').map((s) => s.swimmerId).sort();
  const entered = new Map<string, Set<string>>();
  for (const e of sc.lineup.entries) {
    if (e.teamId === sc.own) continue;
    const set = entered.get(e.teamId) ?? new Set<string>();
    for (const id of e.kind === 'individual' ? [e.swimmerId] : e.legs.map((l) => l.swimmerId)) set.add(id);
    entered.set(e.teamId, set);
  }
  return [
    ...own.slice(0, 3).map((swimmerId) => ({ teamId: sc.own, swimmerId, role: 'scorer' as const })),
    ...[...entered].flatMap(([teamId, ids]) => [...ids].sort().map((swimmerId) => ({ teamId, swimmerId, role: 'scorer' as const }))),
  ];
}

interface Run {
  readonly ms: number;
  readonly result: AutoBuildResult;
}

async function once(sc: Scenario, limits: AutoBuildLimits): Promise<Run> {
  const rules = requireComplete(builtinRulePreset('nsisc', 5) as RulePreset);
  const start = performance.now();
  const result = await autoBuild(
    { model: sc.model, lineup: sc.lineup, rules, sourcing: SOURCING, tags: tagsFor(sc), ownTeamId: sc.own as never, genders: ['Men'], objective: { kind: 'max-own' }, load: null, limits, clock: () => performance.now() },
    nodeMipSolve()
  );
  return { ms: performance.now() - start, result };
}

const f = (n: number): string => n.toFixed(0).padStart(7);

function describeRun(r: Run): string {
  const res = r.result;
  const own = res.kind === 'improved' ? res.proposal.evaluation.ownPoints : res.kind === 'current_infeasible' ? (res.alternative?.evaluation.ownPoints ?? NaN) : res.current.ownPoints;
  const p = res.proof;
  const cols = p.searchSpace.events.reduce((a, e) => a + e.columns, 0);
  const t = p.timings;
  return `${f(r.ms)} ms  ${res.kind.padEnd(10)} own ${String(own).padStart(6)}  ${String(p.status).padEnd(14)} found ${String(p.bestFound)} bound ${String(p.upperBound)} gap ${String(p.gap)}  columns ${cols}  eval ${t.evaluateMs === null ? '-' : f(t.evaluateMs)} ms solve ${t.solveMs === null ? '-' : f(t.solveMs)} ms gate ${t.gateMs === null ? '-' : f(t.gateMs)} ms`;
}

async function scenario(sc: Scenario, limits: AutoBuildLimits, label: string): Promise<number> {
  console.log(`\n=== ${sc.title}\n    ${label}: teams ${sc.model.teams.length}, events ${sc.model.events.length}, entries ${sc.lineup.entries.length}`);
  const times: number[] = [];
  for (let i = 1; i <= RUNS; i++) {
    const r = await once(sc, limits);
    times.push(r.ms);
    console.log(`  run ${i}/${RUNS}: ${describeRun(r)}`);
  }
  const m = median(times);
  console.log(`  median wall ${f(m)} ms: ${m < 10_000 ? 'under' : 'NOT under'} the 10 s acceptance`);
  return m;
}

