/**
 * Everything except the per-entry fields and `write`, which differs per caller.
 * `absWorkingDir` pins the paths esbuild writes into its output comments, so
 * the bytes do not depend on where the build was started.
 */
export const sharedBuildOptions = {
  absWorkingDir: extensionRoot,
  bundle: true,
  platform: 'browser',
  target: ['chrome120'],
  banner: { js: GENERATED_BANNER },
  metafile: true,
  legalComments: 'none',
  minify: false,
  logLevel: 'silent',
  define: { 'process.env.NODE_ENV': '"production"', __OSX_HARNESS__: 'false' },
};

/**
 * The complete esbuild options for one entry. `harness: true` builds into `dist-harness/` with the
 * test probe on; the default is the production build.
 */
export function entryBuildOptions(entry, { harness = false } = {}) {
  return {
    ...sharedBuildOptions,
    define: { ...sharedBuildOptions.define, __OSX_HARNESS__: String(harness) },
    entryPoints: [{ in: entry.in, out: entry.name }],
    outdir: harness ? harnessOutDir : outDir,
    format: entry.format,
    loader: entry.loader,
    ...entry.options,
  };
}
