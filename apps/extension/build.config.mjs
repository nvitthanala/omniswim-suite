import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const extensionRoot = path.dirname(fileURLToPath(import.meta.url));
export const outDir = path.join(extensionRoot, 'dist');
/**
 * The harness build (`build.mjs --harness`): the same extension with `__OSX_HARNESS__` true, so the
 * dashboard installs `globalThis.osxHarness`. Gitignored. Only scripts/run-extension-harness.mjs
 * loads it. The production `dist/` never holds the probe (tests/extensionBundleBoundaries.test.ts).
 */
export const harnessOutDir = path.join(extensionRoot, 'dist-harness');

/** The CommonJS HiGHS glue. esbuild would pick `highs.mjs` (it imports `node:module`), so the worker entry aliases to this file. */
const highsGlue = createRequire(import.meta.url).resolve('highs');
const emptyNodeModule = path.join(extensionRoot, 'src', 'worker', 'emptyNodeModule.ts');

/** Every output is generated. Say so at the top of the file people will open first. */
export const GENERATED_BANNER =
  '// GENERATED by apps/extension/build.mjs. Do not edit.\n' +
  '// Edit the matching file under apps/extension/src/ and re-run `npm run build:extension`.\n';

